/**
 * main.js — Phaser 游戏入口文件
 *
 * 【什么是 Phaser？】
 * Phaser 是一个 HTML5 游戏框架，帮我们处理画布渲染、动画、输入、物理等底层细节，
 * 我们只需要写"场景"和"游戏逻辑"即可。
 *
 * 【运行流程】
 * 1. 浏览器加载本文件 → 创建 Phaser.Game 实例
 * 2. Phaser 自动启动 config.scene 数组中的第一个场景（HomeScene）
 * 3. 各场景通过 this.scene.start('场景名') 互相跳转
 */

/**
 * config — Phaser 游戏配置对象
 * 所有游戏级别的设置都在这里，创建 Game 实例时传入
 * 参考文档：https://docs.phaser.io/api-documentation/typedef/types-core#gameconfig
 */
const config = {

    // =========================================================================
    // type — 渲染模式
    // Phaser.AUTO 会自动尝试 WebGL，不支持则降级到 Canvas
    // 也可手动指定：Phaser.WEBGL / Phaser.CANVAS
    // =========================================================================
    type: Phaser.AUTO,

    // =========================================================================
    // width / height — 游戏世界的逻辑分辨率（单位：像素）
    // 所有坐标、尺寸都基于这个分辨率计算
    // 390×844 是手机竖屏比例，接近主流手机 19.5:9
    // Phaser.Scale.FIT 会等比缩放适配不同屏幕
    // =========================================================================
    width: CONFIG.GAME.WIDTH,
    height: CONFIG.GAME.HEIGHT,

    // =========================================================================
    // parent — 游戏画布要插入的 DOM 容器 id
    // Phaser 会自动在该元素内创建 <canvas>
    // =========================================================================
    parent: 'game-container',

    // =========================================================================
    // backgroundColor — 画布背景色，用十六进制颜色值
    // 当场景内没有覆盖整个画布的背景时，会露出这个颜色
    // =========================================================================
    backgroundColor: CONFIG.GAME.BG,

    // =========================================================================
    // scale — 缩放配置
    //   mode: Phaser.Scale.FIT
    //     - 保持宽高比，等比缩放游戏画面以适配浏览器窗口
    //     - 如果窗口和游戏比例不一致，会出现黑边（letterbox）
    //     其他可选值（了解即可，需要时再查文档）：
    //       Phaser.Scale.NONE          — 不缩放，画布固定大小
    //       Phaser.Scale.RESIZE        — 画布跟随窗口大小变化
    //       Phaser.Scale.EXPAND        — 只放大不缩小
    //
    //   autoCenter: Phaser.Scale.CENTER_BOTH
    //     - 让游戏画布在父容器中水平和垂直居中
    // =========================================================================
    scale: {
        mode: Phaser.Scale.FIT,
        autoCenter: Phaser.Scale.CENTER_BOTH,
    },

    // =========================================================================
    // physics — 物理引擎配置（目前注释掉了，暂时不需要）
    // 解开注释即可启用 Arcade 物理引擎（轻量级，适合大多数 2D 游戏）
    //
    //   default: 'arcade'
    //     - Phaser 内置两种物理引擎：
    //       arcade  — 轻量、简单、性能好（适合平台跳跃、弹幕等）
    //       matter   — 功能更全、更真实（适合物理沙盒、复杂碰撞）
    //
    //   arcade.gravity.y: 300
    //     - 全局重力加速度，y 轴向下为正
    //     - 300 表示每秒速度增加 300 像素
    //
    //   arcade.debug: false
    //     - 设为 true 会在屏幕上绘制碰撞体轮廓（调试用）
    // =========================================================================
    // physics: {
    //     default: 'arcade',
    //     arcade: {
    //         gravity: { y: 300 },
    //         debug: false,
    //     },
    // },

    // =========================================================================
    // scene — 场景列表
    // 注册所有场景类，数组中的第一个场景会自动启动
    // Phaser 要求所有场景必须提前注册，不能动态添加
    // 场景间跳转：this.scene.start('场景key')
    // =========================================================================
    scene: [HomeScene, GameScene],
};

/**
 * game — 全局游戏实例
 *
 * new Phaser.Game(config) 做了以下几件事：
 * 1. 创建 <canvas> 元素并插入到 parent 指定的 DOM 容器
 * 2. 初始化渲染器（WebGL 或 Canvas）
 * 3. 启动场景管理器，开始运行第一个场景的生命周期
 * 4. 开启游戏主循环（每帧调用当前场景的 update 方法）
 *
 * 这个变量挂到全局（没有用 const game = ... 那行前面的 const，实际此处是 const），
 * 意味着在浏览器控制台可以直接输入 game 来调试。
 * 实际开发中你也可以不暴露全局，用即可。
 */
const game = new Phaser.Game(config);
